$resolvedGameRoot = [IO.Path]::GetFullPath($GameRoot)
$paths = Get-GamePaths -Root $resolvedGameRoot

switch ($Action) {
    'Status' {
        if ($Name) {
            throw 'Status does not accept a variant or run label.'
        }
        Invoke-Status -Paths $paths
    }
    'Stage' {
        if ([string]::IsNullOrWhiteSpace($Name)) {
            throw 'Stage requires a variant name.'
        }
        Invoke-Stage -VariantName $Name -Paths $paths -DiagnosticsEnabled $Diagnostics `
            -LoadingScreenModeValue $LoadingScreenMode
    }
    'Archive' {
        if ([string]::IsNullOrWhiteSpace($Name)) {
            throw 'Archive requires a run label.'
        }
        Invoke-Archive -RunLabel $Name -Paths $paths
    }
    'Restore' {
        if ($Name) {
            throw 'Restore does not accept a variant or run label.'
        }
        Invoke-Restore -Paths $paths
    }
    'SelfTest' {
        if ($Name) {
            throw 'SelfTest does not accept a variant or run label.'
        }
        Invoke-SelfTest
    }
}
