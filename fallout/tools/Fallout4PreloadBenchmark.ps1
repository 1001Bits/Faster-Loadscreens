    foreach ($record in @($Session.Manifest.OriginalFiles |
        Where-Object { $_.Role -in @('TopLevelF4SEDll', 'LoadingScreensDll') })) {
        $target = [IO.Path]::GetFullPath([string]$record.Target)
        if ($allowed.Contains($target) -or
            -not (Test-Path -LiteralPath $target -PathType Leaf)) {
            continue
        }
        if ($record.Existed -and
            (Get-Sha256 -LiteralPath $target) -ne [string]$record.Sha256) {
            throw ("An unselected F4SE DLL changed after it was backed up; " +
                "refusing to remove it: $target")
        }
        Remove-Item -LiteralPath $target -Force
    }
}

function Assert-HighFPSPhysicsFixSpeedConfig {
    param([Parameter(Mandatory = $true)][string]$LiteralPath)

    if (-not (Test-Path -LiteralPath $LiteralPath -PathType Leaf)) {
        throw "High FPS Physics Fix INI is missing: $LiteralPath"
    }
    $text = Get-Content -LiteralPath $LiteralPath -Raw
    $requirements = [ordered]@{
        UntieSpeedFromFPS = 'true'
        DisableiFPSClamp = 'true'
        EnableVSync = 'true'
        VSyncPresentInterval = '1'
        AllowTearing = 'true'
        DisableVSyncWhileLoading = 'true'
        DisableBlackLoadingScreens = 'true'
        DisableAnimationOnLoadingScreens = 'true'
        PostloadingMenuSpeed = '2(?:\.0+)?'
        InGameFPS = '0(?:\.0+)?'
        ExteriorFPS = '0(?:\.0+)?'
        InteriorFPS = '0(?:\.0+)?'
        LoadingScreenFPS = '350(?:\.0+)?'
        OneThreadWhileLoading = 'false'
        FramerateLimitMode = '0'
        FixCPUThreads = 'true'
        FixLoadingModel = 'true'
        EnableOSD = 'false'
        LoadingTime = 'false'
        Bare_LoadingTime = 'false'
    }
    foreach ($setting in $requirements.GetEnumerator()) {
        $pattern = '(?im)^\s*' + [Regex]::Escape([string]$setting.Key) +
            '\s*=\s*' + [string]$setting.Value + '\s*(?:[#;].*)?$'
        if ($text -notmatch $pattern) {
            throw ("High FPS Physics Fix speed setting is not in the controlled " +
                "state: {0}" -f $setting.Key)
        }
    }
}

