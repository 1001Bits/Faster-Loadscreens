    $baselineBuffoutProfile = Get-VariantProfile `
        -VariantName 'baseline-buffout'
    Assert-BenchmarkSelfTest `
        -Condition ([int]$baselineBuffoutProfile.BenchmarkMode -eq 0) `
        -Message 'Buffout baseline must keep Faster Loadscreens passive'
    Assert-BenchmarkSelfTest `
        -Condition ([bool]$baselineBuffoutProfile.Buffout4) `
        -Message 'Buffout baseline must enable crash capture'
    Assert-BenchmarkSelfTest `
        -Condition (-not [bool]$baselineBuffoutProfile.NativeLinked -and
                    -not [bool]$baselineBuffoutProfile.PreloadExteriorGates -and
                    -not [bool]$baselineBuffoutProfile.HighFPSPhysicsFix) `
        -Message 'Buffout baseline must disable every preload/speed companion'

    $retiredRejected = $false
