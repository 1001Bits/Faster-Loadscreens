function Assert-TargetRuntime {
    param([Parameter(Mandatory = $true)]$Paths)

    if (-not (Test-Path -LiteralPath $Paths.GameRoot -PathType Container)) {
        throw "Game root does not exist: $($Paths.GameRoot)"
    }
    if (-not (Test-Path -LiteralPath $Paths.Runtime -PathType Leaf)) {
        throw "Fallout4.exe was not found: $($Paths.Runtime)"
    }
    if (-not (Test-Path -LiteralPath $Paths.F4SELoader -PathType Leaf)) {
        throw "f4se_loader.exe was not found: $($Paths.F4SELoader)"
    }

    $actualVersion = (Get-Item -LiteralPath $Paths.Runtime).VersionInfo.FileVersion
    if ($actualVersion -ne $script:ExpectedRuntimeVersion) {
        throw "Expected Fallout 4 $script:ExpectedRuntimeVersion, found $actualVersion at $($Paths.Runtime)"
    }
}

function Get-SourcePaths {
    # Multiple verification build trees may coexist. Never silently stage an
    # older build\Release DLL merely because that conventional path exists;
    # select the newest actual artifact and record its hash in the run manifest.
    $dllCandidates = @(
        (Join-Path $script:WorkspaceRoot 'build\Release\LoadingScreens.dll')
        (Join-Path $script:WorkspaceRoot 'build-verify-final\Release\LoadingScreens.dll')
        (Join-Path $script:WorkspaceRoot 'package\Data\F4SE\Plugins\LoadingScreens.dll')
    )
    $sourceDll = $dllCandidates |
        Where-Object { Test-Path -LiteralPath $_ -PathType Leaf } |
        ForEach-Object { Get-Item -LiteralPath $_ } |
        Sort-Object -Property LastWriteTimeUtc -Descending |
        Select-Object -First 1 -ExpandProperty FullName

    return [ordered]@{
        Dll        = $sourceDll
        ConfigJson = Join-Path $script:WorkspaceRoot 'package\Data\MCM\Config\FasterLoadscreens\config.json'
        SettingsIni = Join-Path $script:WorkspaceRoot 'package\Data\MCM\Config\FasterLoadscreens\settings.ini'
    }
}

