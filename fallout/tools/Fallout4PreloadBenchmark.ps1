function Write-Utf8NoBom {
    param(
        [Parameter(Mandatory = $true)][string]$LiteralPath,
        [Parameter(Mandatory = $true)][string]$Text
    )

    $parent = Split-Path -Parent $LiteralPath
    if ($parent -and -not (Test-Path -LiteralPath $parent -PathType Container)) {
        [void](New-Item -ItemType Directory -Path $parent)
    }
    [IO.File]::WriteAllText($LiteralPath, $Text, [Text.UTF8Encoding]::new($false))
}

function Set-IniValuePreservingFile {
    param(
        [Parameter(Mandatory = $true)][string]$LiteralPath,
        [Parameter(Mandatory = $true)][string]$Section,
        [Parameter(Mandatory = $true)][string]$Key,
        [Parameter(Mandatory = $true)][string]$Value
    )

    if (-not (Test-Path -LiteralPath $LiteralPath -PathType Leaf)) {
        throw "INI file does not exist: $LiteralPath"
    }

    $lines = [Collections.Generic.List[string]]::new()
    foreach ($line in [IO.File]::ReadAllLines($LiteralPath)) {
        $lines.Add($line)
    }

    $sectionHeader = '[' + $Section + ']'
    $sectionStart = -1
    $sectionEnd = $lines.Count
    for ($index = 0; $index -lt $lines.Count; $index++) {
        if ($lines[$index].Trim().Equals(
            $sectionHeader, [StringComparison]::OrdinalIgnoreCase)) {
            $sectionStart = $index
            for ($endIndex = $index + 1; $endIndex -lt $lines.Count; $endIndex++) {
                if ($lines[$endIndex].Trim() -match '^\[.+\]$') {
                    $sectionEnd = $endIndex
                    break
                }
            }
            break
        }
    }
    if ($sectionStart -lt 0) {
        throw "INI section [$Section] was not found in $LiteralPath"
    }

    $escapedKey = [Regex]::Escape($Key)
    $keyPattern = '^\s*' + $escapedKey + '\s*='
    $keyIndex = -1
    for ($index = $sectionStart + 1; $index -lt $sectionEnd; $index++) {
        if ($lines[$index] -match $keyPattern) {
            if ($keyIndex -ge 0) {
                throw "Duplicate [$Section] $Key entries in $LiteralPath"
            }
            $keyIndex = $index
        }
    }
    if ($keyIndex -ge 0) {
        $lines[$keyIndex] = "$Key=$Value"
    } else {
        $lines.Insert($sectionEnd, "$Key=$Value")
    }

    [IO.File]::WriteAllLines(
        $LiteralPath, $lines, [Text.UTF8Encoding]::new($false))
}

