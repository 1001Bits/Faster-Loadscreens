    }

    $fakePaths = [pscustomobject]@{
        InstalledDll = 'C:\self-test\LoadingScreens.dll'
        Buffout4Dll = 'C:\self-test\Buffout4.dll'
        HighFPSPhysicsFixDll = 'C:\self-test\HighFPSPhysicsFix.dll'
    }
    $allowed = @(Get-AllowedActiveF4SEDllPaths `
        -Paths $fakePaths -Profile $profile)
    Assert-BenchmarkSelfTest -Condition ($allowed.Count -eq 1) `
        -Message 'safe B profile must allow exactly one F4SE DLL'
    Assert-BenchmarkSelfTest `
        -Condition ($allowed[0] -eq $fakePaths.InstalledDll) `
        -Message 'the only allowed F4SE DLL must be LoadingScreens.dll'

    $buffoutProfile = Get-VariantProfile -VariantName 'gate-1cell-buffout'
    Assert-BenchmarkSelfTest -Condition ([bool]$buffoutProfile.Buffout4) `
        -Message 'Buffout safe B profile must enable Buffout'
    Assert-BenchmarkSelfTest -Condition (-not [bool]$buffoutProfile.HighFPSPhysicsFix) `
        -Message 'Buffout safe B profile must keep HFPF disabled'
    Assert-BenchmarkSelfTest -Condition (-not [bool]$buffoutProfile.NativeLinked) `
        -Message 'Buffout safe B profile must keep linked/interior preload disabled'
    Assert-BenchmarkSelfTest -Condition ([int]$buffoutProfile.ExteriorGateDistanceCells -eq 0) `
        -Message 'Buffout safe B profile must keep one-cell exterior gate distance'
    $buffoutAllowed = @(Get-AllowedActiveF4SEDllPaths `
        -Paths $fakePaths -Profile $buffoutProfile)
    Assert-BenchmarkSelfTest -Condition ($buffoutAllowed.Count -eq 2) `
        -Message 'Buffout safe B profile must allow exactly two F4SE DLLs'
    Assert-BenchmarkSelfTest `
        -Condition ($buffoutAllowed -contains $fakePaths.InstalledDll -and
                    $buffoutAllowed -contains $fakePaths.Buffout4Dll) `
        -Message 'Buffout safe B profile must allow only LoadingScreens and Buffout4'
