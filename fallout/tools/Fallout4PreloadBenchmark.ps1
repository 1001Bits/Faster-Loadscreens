function Get-VariantProfile {
    param([Parameter(Mandatory = $true)][string]$VariantName)

    $retiredInteriorProfiles = @(
        'native-1cell',
        'native-1cell-buffer1',
        'native-1cell-buffer2',
        'crosshair',
        'plugin-native-1cell',
        'gate-native-grid',
        'candidate-minimal',
        'b-all-preload-buffer3',
        'diagnostic-gate-buffer3',
        'combined-speed-buffer3'
    )
    if ($retiredInteriorProfiles -contains $VariantName) {
        throw ("Benchmark profile '$VariantName' is retired: it selected native " +
            'linked interiors, the historical crosshair path, or the unsafe ' +
            'live-grid exterior mode. Use gate-1cell for the final safe B test.')
    }

    $profiles = @{
        'baseline' = [ordered]@{
            BenchmarkMode = 0; MenuPreload = $true; NativeLinked = $false
            PreloadExteriorGates = $false; ExteriorGateDistanceCells = 0
            InteriorCellBuffer = 3
        }
        'baseline-buffout' = [ordered]@{
            BenchmarkMode = 0; MenuPreload = $true; NativeLinked = $false
            PreloadExteriorGates = $false; ExteriorGateDistanceCells = 0
            InteriorCellBuffer = 3; Buffout4 = $true
        }
        'menu-off' = [ordered]@{
            BenchmarkMode = 0; MenuPreload = $false; NativeLinked = $false
            PreloadExteriorGates = $false; ExteriorGateDistanceCells = 0
            InteriorCellBuffer = 3
        }
        'core' = [ordered]@{
            BenchmarkMode = 1; MenuPreload = $true; NativeLinked = $false
            PreloadExteriorGates = $false; ExteriorGateDistanceCells = 0
            InteriorCellBuffer = 3
        }
        'gate-1cell' = [ordered]@{
            BenchmarkMode = 1; MenuPreload = $true; NativeLinked = $false
            PreloadExteriorGates = $true; ExteriorGateDistanceCells = 0
            InteriorCellBuffer = 3
        }
        'gate-1cell-buffout' = [ordered]@{
            BenchmarkMode = 1; MenuPreload = $true; NativeLinked = $false
            PreloadExteriorGates = $true; ExteriorGateDistanceCells = 0
            InteriorCellBuffer = 3; Buffout4 = $true
        }
        'hfpf-all-speed' = [ordered]@{
            BenchmarkMode = 0; MenuPreload = $true; NativeLinked = $false
            PreloadExteriorGates = $false; ExteriorGateDistanceCells = 0
            InteriorCellBuffer = 3; HighFPSPhysicsFix = $true
        }
    }

    if (-not $profiles.ContainsKey($VariantName)) {
        throw ('Unknown variant "{0}". Expected one of: {1}' -f
            $VariantName, (($profiles.Keys | Sort-Object) -join ', '))
    }

    $profile = $profiles[$VariantName]
    if (-not $profile.Contains('HighFPSPhysicsFix')) {
        $profile['HighFPSPhysicsFix'] = $false
    }
    if (-not $profile.Contains('Buffout4')) {
        $profile['Buffout4'] = $false
    }
    if (-not $profile.Contains('RequireDiagnostics')) {
        $profile['RequireDiagnostics'] = $false
    }
    if ([int]$profile.ExteriorGateDistanceCells -lt 0 -or
        [int]$profile.ExteriorGateDistanceCells -gt 3) {
        throw "Invalid benchmark profile '$VariantName': exterior gate distance stepper must be 0..3."
    }
    if ([int]$profile.InteriorCellBuffer -lt 1 -or
        [int]$profile.InteriorCellBuffer -gt 3) {
        throw "Invalid benchmark profile '$VariantName': interior cell buffer must be 1..3."
    }
    return $profile
}

function Get-ActiveSession {
    if (-not (Test-Path -LiteralPath $script:ActivePointerPath -PathType Leaf)) {
        return $null
    }

    $pointer = Get-Content -LiteralPath $script:ActivePointerPath -Raw | ConvertFrom-Json
    if (-not $pointer.SessionPath) {
        throw "The active-session pointer is invalid: $script:ActivePointerPath"
    }
    $sessionPath = [IO.Path]::GetFullPath([string]$pointer.SessionPath)
    $statePrefix = [IO.Path]::GetFullPath($script:StateRoot).TrimEnd('\') + '\'
    if (-not $sessionPath.StartsWith($statePrefix, [StringComparison]::OrdinalIgnoreCase)) {
        throw "The active session points outside benchmark-state: $sessionPath"
    }
    $manifestPath = Join-Path $sessionPath 'manifest.json'
    if (-not (Test-Path -LiteralPath $manifestPath -PathType Leaf)) {
        throw "The active benchmark manifest is missing: $manifestPath"
    }

    return [pscustomobject]@{
        SessionPath = $sessionPath
        ManifestPath = $manifestPath
        Manifest = (Get-Content -LiteralPath $manifestPath -Raw | ConvertFrom-Json)
    }
}

