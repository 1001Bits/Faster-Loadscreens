function Resolve-SessionRelativePath {
    param(
        [Parameter(Mandatory = $true)][string]$SessionPath,
        [Parameter(Mandatory = $true)][string]$RelativePath
    )

    $sessionFull = [IO.Path]::GetFullPath($SessionPath)
    $resolved = [IO.Path]::GetFullPath((Join-Path $sessionFull $RelativePath))
    $prefix = $sessionFull.TrimEnd('\') + '\'
    if (-not $resolved.StartsWith($prefix, [StringComparison]::OrdinalIgnoreCase)) {
        throw "Manifest path escapes its session directory: $RelativePath"
    }
    return $resolved
}

function New-OriginalFileRecord {
    param(
        [Parameter(Mandatory = $true)][string]$Role,
        [Parameter(Mandatory = $true)][string]$Target,
        [Parameter(Mandatory = $true)][string]$BackupRelative
    )

    $exists = Test-Path -LiteralPath $Target -PathType Leaf
    $record = [ordered]@{
        Role = $Role
        Target = $Target
        Existed = $exists
        BackupRelative = $BackupRelative
        Sha256 = $null
        Length = $null
        LastWriteTimeUtc = $null
        Attributes = $null
    }
    if ($exists) {
        $item = Get-Item -LiteralPath $Target
        $record.Sha256 = Get-Sha256 -LiteralPath $Target
        $record.Length = $item.Length
        $record.LastWriteTimeUtc = $item.LastWriteTimeUtc.ToString('o')
        $record.Attributes = [int]$item.Attributes
    }
    return $record
}

function Backup-OriginalRecord {
    param(
        [Parameter(Mandatory = $true)][string]$SessionPath,
        [Parameter(Mandatory = $true)]$Record
    )

    if (-not $Record.Existed) {
        return
    }
    $backupPath = Resolve-SessionRelativePath -SessionPath $SessionPath -RelativePath $Record.BackupRelative
    $parent = Split-Path -Parent $backupPath
    if (-not (Test-Path -LiteralPath $parent -PathType Container)) {
        [void](New-Item -ItemType Directory -Path $parent)
    }
    Copy-Item -LiteralPath $Record.Target -Destination $backupPath
    $backupHash = Get-Sha256 -LiteralPath $backupPath
    if ($backupHash -ne $Record.Sha256) {
        throw "Backup verification failed for $($Record.Target)"
    }
}

function New-BenchmarkSession {
    param(
        [Parameter(Mandatory = $true)]$Paths
    )

    if (-not (Test-Path -LiteralPath $script:StateRoot -PathType Container)) {
        [void](New-Item -ItemType Directory -Path $script:StateRoot)
    }
    if (Test-Path -LiteralPath $script:ActivePointerPath) {
        throw "An active benchmark session already exists: $script:ActivePointerPath"
    }

    $stamp = (Get-Date).ToUniversalTime().ToString('yyyyMMdd-HHmmss-fff')
    $sessionPath = Join-Path $script:StateRoot $stamp
    [void](New-Item -ItemType Directory -Path $sessionPath)

    $records = [System.Collections.Generic.List[object]]::new()
    $trackedTargets = [System.Collections.Generic.HashSet[string]]::new(
        [StringComparer]::OrdinalIgnoreCase)

    $activeDlls = @()
    if (Test-Path -LiteralPath $Paths.F4SEPlugins -PathType Container) {
        $activeDlls = @(Get-ChildItem -LiteralPath $Paths.F4SEPlugins -File -Filter '*.dll' |
            Sort-Object -Property Name)
    }
    foreach ($dll in $activeDlls) {
        $relative = 'original\f4se-dlls\' + $dll.Name
        $records.Add((New-OriginalFileRecord -Role 'TopLevelF4SEDll' `
            -Target $dll.FullName -BackupRelative $relative))
        [void]$trackedTargets.Add($dll.FullName)
    }
    if (-not $trackedTargets.Contains($Paths.InstalledDll)) {
        $records.Add((New-OriginalFileRecord -Role 'LoadingScreensDll' `
            -Target $Paths.InstalledDll `
            -BackupRelative 'original\f4se-dlls\LoadingScreens.dll'))
        [void]$trackedTargets.Add($Paths.InstalledDll)
    }

    $managed = @(
        @('PluginList', $Paths.PluginsTxt, 'original\configuration\plugins.txt'),
        @('Fallout4Ini', $Paths.FalloutIni, 'original\configuration\Fallout4.ini'),
        @('Fallout4PrefsIni', $Paths.FalloutPrefs, 'original\configuration\Fallout4Prefs.ini'),
        @('Fallout4CustomIni', $Paths.FalloutCustom, 'original\configuration\Fallout4Custom.ini'),
        @('PackageConfig', $Paths.PackageConfig, 'original\configuration\config.json'),
        @('PackageSettings', $Paths.PackageIni, 'original\configuration\settings.ini'),
        @('UserMcmSettings', $Paths.UserMcmIni, 'original\configuration\FasterLoadscreens.ini'),
        @('Buffout4Config', $Paths.Buffout4Toml,
            'original\configuration\Buffout4.toml'),
        @('HighFPSPhysicsFixIni', $Paths.HighFPSPhysicsFixIni,
            'original\configuration\HighFPSPhysicsFix.ini')
    )
    foreach ($entry in $managed) {
        $records.Add((New-OriginalFileRecord -Role $entry[0] -Target $entry[1] `
            -BackupRelative $entry[2]))
    }

    foreach ($record in $records) {
        Backup-OriginalRecord -SessionPath $sessionPath -Record $record
    }

    $manifest = [ordered]@{
        SchemaVersion = 1
        CreatedUtc = (Get-Date).ToUniversalTime().ToString('o')
        WorkspaceRoot = $script:WorkspaceRoot
        GameRoot = $Paths.GameRoot
        RuntimeVersion = (Get-Item -LiteralPath $Paths.Runtime).VersionInfo.FileVersion
        OriginalFiles = @($records)
        CurrentVariant = $null
        CurrentDiagnostics = $null
        StageHistory = @()
        ArchiveHistory = @()
        RestoredUtc = $null
    }
    $manifestPath = Join-Path $sessionPath 'manifest.json'
    Write-JsonAtomic -LiteralPath $manifestPath -Value $manifest
    Write-JsonAtomic -LiteralPath $script:ActivePointerPath -Value ([ordered]@{
        SessionPath = $sessionPath
        CreatedUtc = $manifest.CreatedUtc
    })

    return [pscustomobject]@{
        SessionPath = $sessionPath
        ManifestPath = $manifestPath
        Manifest = (Get-Content -LiteralPath $manifestPath -Raw | ConvertFrom-Json)
    }
}

function Assert-SessionMatchesTarget {
    param(
        [Parameter(Mandatory = $true)]$Session,
        [Parameter(Mandatory = $true)]$Paths
    )

    if (-not ([string]$Session.Manifest.WorkspaceRoot).Equals(
        $script:WorkspaceRoot, [StringComparison]::OrdinalIgnoreCase)) {
        throw "The active session belongs to another workspace: $($Session.Manifest.WorkspaceRoot)"
    }
    if (-not ([string]$Session.Manifest.GameRoot).Equals(
        $Paths.GameRoot, [StringComparison]::OrdinalIgnoreCase)) {
        throw "The active session targets another game root: $($Session.Manifest.GameRoot)"
    }
    if ($Session.Manifest.RestoredUtc) {
        throw "The active pointer references a session already marked restored: $($Session.SessionPath)"
    }
}

function Assert-OriginalBackups {
    param([Parameter(Mandatory = $true)]$Session)

    foreach ($record in @($Session.Manifest.OriginalFiles)) {
        if (-not $record.Existed) {
            continue
        }
        $backupPath = Resolve-SessionRelativePath -SessionPath $Session.SessionPath `
            -RelativePath ([string]$record.BackupRelative)
        if (-not (Test-Path -LiteralPath $backupPath -PathType Leaf)) {
            throw "Original backup is missing: $backupPath"
        }
        if ((Get-Sha256 -LiteralPath $backupPath) -ne [string]$record.Sha256) {
            throw "Original backup hash mismatch: $backupPath"
        }
    }
}

function Disable-OriginalF4SEDlls {
    param([Parameter(Mandatory = $true)]$Session)

    foreach ($record in @($Session.Manifest.OriginalFiles |
        Where-Object { $_.Role -in @('TopLevelF4SEDll', 'LoadingScreensDll') })) {
        if (-not (Test-Path -LiteralPath $record.Target -PathType Leaf)) {
            continue
        }
        if ($record.Existed -and (Get-Sha256 -LiteralPath $record.Target) -ne [string]$record.Sha256) {
            throw "An F4SE DLL changed after it was backed up; refusing to remove it: $($record.Target)"
        }
        Remove-Item -LiteralPath $record.Target -Force
    }
}

