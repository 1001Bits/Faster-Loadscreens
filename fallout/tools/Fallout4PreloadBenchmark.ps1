        'fNormalDoorFadeWait=0.01',
        'bPreloadExteriorGates=1',
        'iExteriorGateDistanceCells=0',
        'bPreloadDiagnostics=0'
    )) {
        Assert-BenchmarkTextLine -Text $mcm -Expected $line
    }

    $custom = New-ControlledCustomIniText `
        -VariantName $variant -Profile $profile
    foreach ($line in @(
        'bUseMenuLoadCellPreload=1',
        'bPreloadLinkedAreas=0',
        'fTeleportPreloadDistance=2048.0000',
        'uGridsToLoad=5',
        'uInterior Cell Buffer=3',
