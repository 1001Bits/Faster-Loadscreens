function Write-JsonAtomic {
    param(
        [Parameter(Mandatory = $true)][string]$LiteralPath,
        [Parameter(Mandatory = $true)]$Value
    )

    $json = $Value | ConvertTo-Json -Depth 12
    $temporaryPath = "$LiteralPath.tmp"
    Write-Utf8NoBom -LiteralPath $temporaryPath -Text ($json + [Environment]::NewLine)
    Move-Item -LiteralPath $temporaryPath -Destination $LiteralPath -Force
}

function Get-Sha256 {
    param([Parameter(Mandatory = $true)][string]$LiteralPath)
    return (Get-FileHash -LiteralPath $LiteralPath -Algorithm SHA256).Hash
}

function Get-RunningGameProcesses {
    $names = @('Fallout4', 'Fallout4Launcher', 'f4se_loader', 'f4se_steam_loader')
    $found = foreach ($processName in $names) {
        Get-Process -Name $processName -ErrorAction SilentlyContinue
    }
    return @($found | Sort-Object -Property Id -Unique)
}

function Assert-GameStopped {
    $running = @(Get-RunningGameProcesses)
    if ($running.Count -gt 0) {
        $descriptions = $running | ForEach-Object { '{0} (PID {1})' -f $_.ProcessName, $_.Id }
        throw ('Fallout 4/F4SE is running: {0}. Exit it completely before this action.' -f
            ($descriptions -join ', '))
    }
}

