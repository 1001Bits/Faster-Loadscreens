        -Condition ($script:ControlledPresentInterval -eq 1) `
        -Message 'controlled present interval must be 1'
    Assert-BenchmarkSelfTest `
        -Condition ($script:ControlledBorderless -eq 1 -and
                    $script:ControlledFullScreen -eq 0 -and
