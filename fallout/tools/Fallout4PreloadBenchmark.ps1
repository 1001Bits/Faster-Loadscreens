function Install-Variant {
    param(
        [Parameter(Mandatory = $true)][string]$VariantName,
        [Parameter(Mandatory = $true)]$Profile,
        [Parameter(Mandatory = $true)]$Paths,
        [Parameter(Mandatory = $true)]$Sources,
        [Parameter(Mandatory = $true)]$Session,
        [Parameter(Mandatory = $true)][bool]$DiagnosticsEnabled,
        [Parameter(Mandatory = $true)][int]$LoadingScreenModeValue
    )

    Assert-OriginalBackups -Session $Session
    $allowedDllPaths = Get-AllowedActiveF4SEDllPaths -Paths $Paths -Profile $Profile
    Assert-NoUnexpectedActiveDlls -Paths $Paths -Session $Session `
        -AllowedDllPaths $allowedDllPaths

    foreach ($directory in @(
        $Paths.F4SEPlugins,
        (Split-Path -Parent $Paths.PackageConfig),
        (Split-Path -Parent $Paths.UserMcmIni),
        (Split-Path -Parent $Paths.PluginsTxt),
        (Split-Path -Parent $Paths.FalloutCustom)
    )) {
        if (-not (Test-Path -LiteralPath $directory -PathType Container)) {
            [void](New-Item -ItemType Directory -Path $directory)
        }
    }

    Copy-Item -LiteralPath $Sources.Dll -Destination $Paths.InstalledDll -Force
    $buffout4Hash = $null
    if ([bool]$Profile.Buffout4) {
        $buffoutRecords = @($Session.Manifest.OriginalFiles | Where-Object {
            $_.Role -eq 'TopLevelF4SEDll' -and
            ([IO.Path]::GetFileName([string]$_.Target)).Equals(
                'Buffout4.dll', [StringComparison]::OrdinalIgnoreCase)
        })
        if ($buffoutRecords.Count -ne 1 -or -not $buffoutRecords[0].Existed) {
            throw 'The benchmark session has no verified original Buffout4.dll backup.'
        }
        $buffoutBackup = Resolve-SessionRelativePath `
            -SessionPath $Session.SessionPath `
            -RelativePath ([string]$buffoutRecords[0].BackupRelative)
        Copy-Item -LiteralPath $buffoutBackup `
            -Destination $Paths.Buffout4Dll -Force
        $buffout4Hash = Get-Sha256 -LiteralPath $Paths.Buffout4Dll
        if ($buffout4Hash -ne [string]$buffoutRecords[0].Sha256) {
            throw 'Installed Buffout4.dll does not match its verified session backup.'
        }
        Write-Utf8NoBom -LiteralPath $Paths.Buffout4Toml `
            -Text (New-ControlledBuffout4TomlText)
        Assert-BuffoutCrashCaptureConfig -LiteralPath $Paths.Buffout4Toml
    }
    $highFPSPhysicsFixHash = $null
    if ([bool]$Profile.HighFPSPhysicsFix) {
        $highFPSRecords = @($Session.Manifest.OriginalFiles | Where-Object {
            $_.Role -eq 'TopLevelF4SEDll' -and
            ([IO.Path]::GetFileName([string]$_.Target)).Equals(
                'HighFPSPhysicsFix.dll', [StringComparison]::OrdinalIgnoreCase)
        })
        if ($highFPSRecords.Count -ne 1 -or -not $highFPSRecords[0].Existed) {
            throw 'The benchmark session has no verified original HighFPSPhysicsFix.dll backup.'
        }
        $highFPSIniRecords = @($Session.Manifest.OriginalFiles | Where-Object {
            $_.Role -eq 'HighFPSPhysicsFixIni'
        })
        if ($highFPSIniRecords.Count -ne 1 -or
            -not $highFPSIniRecords[0].Existed) {
            throw ('The benchmark session has no verified original ' +
                'HighFPSPhysicsFix.ini backup. Restore and start a new session.')
        }
        $highFPSBackup = Resolve-SessionRelativePath `
            -SessionPath $Session.SessionPath `
            -RelativePath ([string]$highFPSRecords[0].BackupRelative)
        Copy-Item -LiteralPath $highFPSBackup `
            -Destination $Paths.HighFPSPhysicsFixDll -Force
        $highFPSPhysicsFixHash = Get-Sha256 -LiteralPath $Paths.HighFPSPhysicsFixDll
        if ($highFPSPhysicsFixHash -ne [string]$highFPSRecords[0].Sha256) {
            throw 'Installed HighFPSPhysicsFix.dll does not match its verified session backup.'
        }
        Set-HighFPSPhysicsFixSpeedConfig `
            -LiteralPath $Paths.HighFPSPhysicsFixIni
        Assert-HighFPSPhysicsFixSpeedConfig `
            -LiteralPath $Paths.HighFPSPhysicsFixIni
    }
    Copy-Item -LiteralPath $Sources.ConfigJson -Destination $Paths.PackageConfig -Force
    Copy-Item -LiteralPath $Sources.SettingsIni -Destination $Paths.PackageIni -Force

    Write-Utf8NoBom -LiteralPath $Paths.UserMcmIni `
        -Text (New-UserMcmText -VariantName $VariantName -Profile $Profile `
            -SessionPath $Session.SessionPath -DiagnosticsEnabled $DiagnosticsEnabled `
            -LoadingScreenModeValue $LoadingScreenModeValue)
    Write-Utf8NoBom -LiteralPath $Paths.FalloutCustom `
        -Text (New-ControlledCustomIniText -VariantName $VariantName -Profile $Profile)
    $presentIntervalValue = [string]$script:ControlledPresentInterval
    Set-IniValuePreservingFile -LiteralPath $Paths.FalloutIni `
        -Section 'Display' -Key 'iPresentInterval' -Value $presentIntervalValue
    Set-IniValuePreservingFile -LiteralPath $Paths.FalloutPrefs `
        -Section 'Display' -Key 'iPresentInterval' -Value $presentIntervalValue
    Set-IniValuePreservingFile -LiteralPath $Paths.FalloutPrefs `
        -Section 'Display' -Key 'bBorderless' `
        -Value ([string]$script:ControlledBorderless)
    Set-IniValuePreservingFile -LiteralPath $Paths.FalloutPrefs `
        -Section 'Display' -Key 'bFull Screen' `
        -Value ([string]$script:ControlledFullScreen)
    Set-IniValuePreservingFile -LiteralPath $Paths.FalloutPrefs `
        -Section 'Display' -Key 'bMaximizeWindow' `
        -Value ([string]$script:ControlledMaximizeWindow)
    Write-Utf8NoBom -LiteralPath $Paths.PluginsTxt -Text @"
# Generated for the Faster Loadscreens controlled benchmark.
# All non-default ESP/ESL plugins are intentionally disabled.
"@

    $remainingDlls = @(Get-ChildItem -LiteralPath $Paths.F4SEPlugins -File -Filter '*.dll')
    $allowedDllSet = [System.Collections.Generic.HashSet[string]]::new(
        [StringComparer]::OrdinalIgnoreCase)
    foreach ($path in $allowedDllPaths) {
        [void]$allowedDllSet.Add([IO.Path]::GetFullPath($path))
    }
    $unexpectedDlls = @($remainingDlls | Where-Object {
        -not $allowedDllSet.Contains($_.FullName)
    })
    if ($remainingDlls.Count -ne $allowedDllSet.Count -or
        $unexpectedDlls.Count -gt 0) {
        throw ('Isolation verification failed: active top-level F4SE DLLs do not ' +
            'match the selected profile.')
    }

    $installedHash = Get-Sha256 -LiteralPath $Paths.InstalledDll
    $sourceHash = Get-Sha256 -LiteralPath $Sources.Dll
    if ($installedHash -ne $sourceHash) {
        throw 'Installed LoadingScreens.dll does not match the selected workspace DLL.'
    }

    $entry = [ordered]@{
        Variant = $VariantName
        StagedUtc = (Get-Date).ToUniversalTime().ToString('o')
        BenchmarkMode = [int]$Profile.BenchmarkMode
        LoadingScreenMode = $LoadingScreenModeValue
        MenuPreload = [bool]$Profile.MenuPreload
        NativeLinked = [bool]$Profile.NativeLinked
        InteriorCellBuffer = [int]$Profile.InteriorCellBuffer
        PresentInterval = $script:ControlledPresentInterval
        DisplayMode = 'borderless-windowed'
        Borderless = $script:ControlledBorderless
        FullScreen = $script:ControlledFullScreen
        MaximizeWindow = $script:ControlledMaximizeWindow
        HighFPSPhysicsFix = [bool]$Profile.HighFPSPhysicsFix
        HighFPSPhysicsFixSha256 = $highFPSPhysicsFixHash
        Buffout4 = [bool]$Profile.Buffout4
        Buffout4Sha256 = $buffout4Hash
        Buffout4ConfigSha256 = if ([bool]$Profile.Buffout4) {
            Get-Sha256 -LiteralPath $Paths.Buffout4Toml
        } else {
            $null
        }
        ExteriorGate = [bool]$Profile.PreloadExteriorGates
        ExteriorGateDistanceStepper = [int]$Profile.ExteriorGateDistanceCells
        ExteriorGateDistanceCells = [int]$Profile.ExteriorGateDistanceCells + 1
        ExteriorPreloadMode = 'engine-single-cell'
        Diagnostics = $DiagnosticsEnabled
        SourceDll = $Sources.Dll
        SourceDllSha256 = $sourceHash
    }
    $Session.Manifest.CurrentVariant = $VariantName
    $Session.Manifest.CurrentDiagnostics = $DiagnosticsEnabled
    $Session.Manifest.StageHistory = @($Session.Manifest.StageHistory) + @($entry)
    Write-JsonAtomic -LiteralPath $Session.ManifestPath -Value $Session.Manifest
    $Session.Manifest = Get-Content -LiteralPath $Session.ManifestPath -Raw | ConvertFrom-Json

    return $entry
}

function Invoke-Stage {
    param(
        [Parameter(Mandatory = $true)][string]$VariantName,
        [Parameter(Mandatory = $true)]$Paths,
        [Parameter(Mandatory = $true)][bool]$DiagnosticsEnabled,
        [Parameter(Mandatory = $true)][int]$LoadingScreenModeValue
    )

    Assert-GameStopped
    Assert-TargetRuntime -Paths $Paths
    $sources = Get-SourcePaths
    Assert-SourceFiles -Sources $sources
    $profile = Get-VariantProfile -VariantName $VariantName
    Assert-ProfileInvocation -VariantName $VariantName -Profile $profile `
        -DiagnosticsEnabled $DiagnosticsEnabled
    $allowedDllPaths = Get-AllowedActiveF4SEDllPaths `
        -Paths $Paths -Profile $profile

    $session = Get-ActiveSession
    $newSession = $false
    if ($null -eq $session) {
        $session = New-BenchmarkSession -Paths $Paths
        $newSession = $true
    } else {
        Assert-SessionMatchesTarget -Session $session -Paths $Paths
    }

    try {
        if ($newSession) {
            Disable-OriginalF4SEDlls -Session $session
        } else {
            Disable-UnselectedOriginalF4SEDlls -Session $session `
                -AllowedDllPaths $allowedDllPaths
            Assert-NoUnexpectedActiveDlls -Paths $Paths -Session $session `
                -AllowedDllPaths $allowedDllPaths
        }
        $entry = Install-Variant -VariantName $VariantName -Profile $profile `
            -Paths $Paths -Sources $sources -Session $session `
            -DiagnosticsEnabled $DiagnosticsEnabled `
            -LoadingScreenModeValue $LoadingScreenModeValue
    } catch {
        throw ("Stage failed. The original files are preserved in {0}; run Restore after " +
            "resolving the reported problem.`n{1}" -f $session.SessionPath, $_.Exception.Message)
    }

    Write-Host "Staged '$VariantName' for Fallout 4 $script:ExpectedRuntimeVersion."
    Write-Host "Session: $($session.SessionPath)"
    Write-Host "LoadingScreens.dll SHA-256: $($entry.SourceDllSha256)"
    Write-Host (('Controls: benchmark={0}, loadscreen-mode={1}, menu={2}, ' +
        'native-linked={3}, interior-buffer={4}, exterior-gate={5}, ' +
        'gate-distance={6} cell(s), exterior-preload={7}, diagnostics={8}, ' +
        'hfpf={9}, buffout={10}') -f
        $entry.BenchmarkMode, $entry.LoadingScreenMode, $entry.MenuPreload,
        $entry.NativeLinked, $entry.InteriorCellBuffer,
        $entry.ExteriorGate, $entry.ExteriorGateDistanceCells,
        $entry.ExteriorPreloadMode, $entry.Diagnostics,
        $entry.HighFPSPhysicsFix, $entry.Buffout4)
    Write-Host 'Unselected top-level F4SE DLLs, active plugins, and loose-file invalidation are disabled.'
    Write-Host 'Launch with f4se_loader.exe; fully exit the game before Archive or another Stage.'
}

function Copy-ArchiveFile {
    param(
        [Parameter(Mandatory = $true)][string]$Source,
        [Parameter(Mandatory = $true)][string]$Destination,
        [Parameter(Mandatory = $true)]
        [AllowEmptyCollection()]
        [System.Collections.Generic.List[object]]$Records
    )

    if (-not (Test-Path -LiteralPath $Source -PathType Leaf)) {
        return
    }
    $parent = Split-Path -Parent $Destination
    if (-not (Test-Path -LiteralPath $parent -PathType Container)) {
        [void](New-Item -ItemType Directory -Path $parent)
    }
    Copy-Item -LiteralPath $Source -Destination $Destination
    $Records.Add([ordered]@{
        Source = $Source
        ArchivedAs = $Destination
        Sha256 = Get-Sha256 -LiteralPath $Destination
        Length = (Get-Item -LiteralPath $Destination).Length
        LastWriteTimeUtc = (Get-Item -LiteralPath $Source).LastWriteTimeUtc.ToString('o')
    })
}

function Invoke-Archive {
    param(
        [Parameter(Mandatory = $true)][string]$RunLabel,
        [Parameter(Mandatory = $true)]$Paths
    )

    Assert-GameStopped
    if ($RunLabel -notmatch '^[A-Za-z0-9][A-Za-z0-9._-]{0,63}$') {
        throw 'Run label must be 1-64 characters using letters, numbers, dot, underscore, or hyphen.'
    }
    $session = Get-ActiveSession
    if ($null -eq $session) {
        throw 'There is no active benchmark session to archive.'
    }
    Assert-SessionMatchesTarget -Session $session -Paths $Paths

    $stamp = (Get-Date).ToUniversalTime().ToString('yyyyMMdd-HHmmss-fff')
    $runPath = Join-Path $session.SessionPath ('runs\' + $stamp + '-' + $RunLabel)
    [void](New-Item -ItemType Directory -Path $runPath)
    $records = [System.Collections.Generic.List[object]]::new()

    $logCandidates = @(
        (Join-Path $Paths.F4SELogDir 'LoadingScreens.log'),
        (Join-Path $Paths.F4SELogDir 'LoadingScreens.prev.log'),
        (Join-Path $Paths.F4SELogDir 'f4se.log'),
        (Join-Path $Paths.F4SELogDir 'f4se_loader.log')
    )
    $currentStage = @($session.Manifest.StageHistory) | Select-Object -Last 1
    $buffoutActive = $null -ne $currentStage -and
        $currentStage.PSObject.Properties.Name -contains 'Buffout4' -and
        [bool]$currentStage.Buffout4
    if ($buffoutActive) {
        $logCandidates += $Paths.Buffout4Log
        $stagedUtc = [DateTime]::Parse(
            [string]$currentStage.StagedUtc,
            [Globalization.CultureInfo]::InvariantCulture,
            [Globalization.DateTimeStyles]::RoundtripKind).ToUniversalTime()
        $logCandidates += @(Get-ChildItem -LiteralPath $Paths.F4SELogDir `
            -File -Filter 'crash-*.log' -ErrorAction SilentlyContinue | Where-Object {
                $_.LastWriteTimeUtc -ge $stagedUtc
            } | Select-Object -ExpandProperty FullName)
    }
    foreach ($logPath in $logCandidates) {
        Copy-ArchiveFile -Source $logPath `
            -Destination (Join-Path $runPath ('logs\' + (Split-Path -Leaf $logPath))) `
            -Records $records
    }

    $configuration = @(
        [pscustomobject]@{
            Source = $Paths.UserMcmIni
            Relative = 'configuration\FasterLoadscreens.ini'
        }
        [pscustomobject]@{
            Source = $Paths.PackageIni
            Relative = 'configuration\settings.ini'
        }
        [pscustomobject]@{
            Source = $Paths.PackageConfig
            Relative = 'configuration\config.json'
        }
        [pscustomobject]@{
            Source = $Paths.FalloutCustom
            Relative = 'configuration\Fallout4Custom.ini'
        }
        [pscustomobject]@{
            Source = $Paths.FalloutIni
            Relative = 'configuration\Fallout4.ini'
        }
        [pscustomobject]@{
            Source = $Paths.FalloutPrefs
            Relative = 'configuration\Fallout4Prefs.ini'
        }
        [pscustomobject]@{
            Source = $Paths.HighFPSPhysicsFixIni
            Relative = 'configuration\HighFPSPhysicsFix.ini'
        }
        [pscustomobject]@{
            Source = $Paths.PluginsTxt
            Relative = 'configuration\plugins.txt'
        }
        [pscustomobject]@{
            Source = $Paths.InstalledDll
            Relative = 'plugin\LoadingScreens.dll'
        }
    )
    if (Test-Path -LiteralPath $Paths.HighFPSPhysicsFixDll -PathType Leaf) {
        $configuration += [pscustomobject]@{
            Source = $Paths.HighFPSPhysicsFixDll
            Relative = 'plugin\HighFPSPhysicsFix.dll'
        }
    }
    if ($buffoutActive) {
        $configuration += [pscustomobject]@{
            Source = $Paths.Buffout4Dll
            Relative = 'plugin\Buffout4.dll'
        }
        $configuration += [pscustomobject]@{
            Source = $Paths.Buffout4Toml
            Relative = 'configuration\Buffout4.toml'
        }
    }
    foreach ($item in $configuration) {
        Copy-ArchiveFile -Source $item.Source `
            -Destination (Join-Path $runPath $item.Relative) `
            -Records $records
    }

    # Hash the runtime/toolchain in place instead of copying Fallout4.exe into
    # every repeat archive.
    $evidence = [System.Collections.Generic.List[object]]::new()
    foreach ($evidencePath in @(
        $Paths.Runtime,
        $Paths.F4SELoader,
        $Paths.InstalledDll,
        $Paths.Buffout4Dll,
        $Paths.HighFPSPhysicsFixDll
    )) {
        if (-not (Test-Path -LiteralPath $evidencePath -PathType Leaf)) {
            continue
        }
        $item = Get-Item -LiteralPath $evidencePath
        $evidence.Add([ordered]@{
            Path = $evidencePath
            Sha256 = Get-Sha256 -LiteralPath $evidencePath
            Length = $item.Length
            LastWriteTimeUtc = $item.LastWriteTimeUtc.ToString('o')
            FileVersion = $item.VersionInfo.FileVersion
        })
    }

    $runMetadata = [ordered]@{
        SchemaVersion = 1
        Label = $RunLabel
        Variant = $session.Manifest.CurrentVariant
        Diagnostics = $session.Manifest.CurrentDiagnostics
        ArchivedUtc = (Get-Date).ToUniversalTime().ToString('o')
        SessionPath = $session.SessionPath
        GameRoot = $Paths.GameRoot
        RuntimeVersion = (Get-Item -LiteralPath $Paths.Runtime).VersionInfo.FileVersion
        Files = @($records)
        Evidence = @($evidence)
    }
    Write-JsonAtomic -LiteralPath (Join-Path $runPath 'run.json') -Value $runMetadata

    $archiveEntry = [ordered]@{
        Label = $RunLabel
        Variant = $session.Manifest.CurrentVariant
        Diagnostics = $session.Manifest.CurrentDiagnostics
        ArchivedUtc = $runMetadata.ArchivedUtc
        RunPath = $runPath
        FileCount = $records.Count
    }
    $session.Manifest.ArchiveHistory = @($session.Manifest.ArchiveHistory) + @($archiveEntry)
    Write-JsonAtomic -LiteralPath $session.ManifestPath -Value $session.Manifest

    Write-Host "Archived '$RunLabel' ($($session.Manifest.CurrentVariant)) to:"
    Write-Host $runPath
    if (-not (Test-Path -LiteralPath $Paths.LoadingLog -PathType Leaf)) {
        Write-Warning 'LoadingScreens.log was not present; the archive still contains the staged configuration and hashes.'
    }
}

function Save-PreRestoreFiles {
    param(
        [Parameter(Mandatory = $true)]$Paths,
        [Parameter(Mandatory = $true)]$Session
    )

    $stamp = (Get-Date).ToUniversalTime().ToString('yyyyMMdd-HHmmss-fff')
    $saveRoot = Join-Path $Session.SessionPath ('pre-restore\' + $stamp)
    $targets = [System.Collections.Generic.List[string]]::new()
    foreach ($record in @($Session.Manifest.OriginalFiles)) {
        if (Test-Path -LiteralPath $record.Target -PathType Leaf) {
            $targets.Add([string]$record.Target)
        }
    }
    if (Test-Path -LiteralPath $Paths.F4SEPlugins -PathType Container) {
        foreach ($dll in @(Get-ChildItem -LiteralPath $Paths.F4SEPlugins -File -Filter '*.dll')) {
            if (-not $targets.Contains($dll.FullName)) {
                $targets.Add($dll.FullName)
            }
        }
    }

    $index = 0
    foreach ($target in $targets) {
        $leaf = Split-Path -Leaf $target
        $destination = Join-Path $saveRoot ('{0:D3}-{1}' -f $index, $leaf)
        $parent = Split-Path -Parent $destination
        if (-not (Test-Path -LiteralPath $parent -PathType Container)) {
            [void](New-Item -ItemType Directory -Path $parent)
        }
        Copy-Item -LiteralPath $target -Destination $destination
        $index++
    }
    return $saveRoot
}

function Restore-OriginalRecord {
    param(
        [Parameter(Mandatory = $true)][string]$SessionPath,
        [Parameter(Mandatory = $true)]$Record
    )

    if ($Record.Existed) {
        $backupPath = Resolve-SessionRelativePath -SessionPath $SessionPath `
            -RelativePath ([string]$Record.BackupRelative)
        if (-not (Test-Path -LiteralPath $backupPath -PathType Leaf)) {
            throw "Cannot restore missing backup: $backupPath"
        }
        if ((Get-Sha256 -LiteralPath $backupPath) -ne [string]$Record.Sha256) {
            throw "Cannot restore corrupted backup: $backupPath"
        }
        $parent = Split-Path -Parent ([string]$Record.Target)
        if (-not (Test-Path -LiteralPath $parent -PathType Container)) {
            [void](New-Item -ItemType Directory -Path $parent)
        }
        Copy-Item -LiteralPath $backupPath -Destination $Record.Target -Force
        $restored = Get-Item -LiteralPath $Record.Target
        if ($Record.LastWriteTimeUtc -is [DateTime]) {
            $restored.LastWriteTimeUtc =
                ([DateTime]$Record.LastWriteTimeUtc).ToUniversalTime()
        } else {
            $restored.LastWriteTimeUtc = [DateTime]::Parse(
                [string]$Record.LastWriteTimeUtc,
                [Globalization.CultureInfo]::InvariantCulture,
                [Globalization.DateTimeStyles]::RoundtripKind)
        }
        $restored.Attributes = [IO.FileAttributes]([int]$Record.Attributes)
        if ((Get-Sha256 -LiteralPath $Record.Target) -ne [string]$Record.Sha256) {
            throw "Restored file verification failed: $($Record.Target)"
        }
    } elseif (Test-Path -LiteralPath $Record.Target -PathType Leaf) {
        Remove-Item -LiteralPath $Record.Target -Force
    }
}

function Invoke-Restore {
    param([Parameter(Mandatory = $true)]$Paths)

    Assert-GameStopped
    $session = Get-ActiveSession
    if ($null -eq $session) {
        Write-Host 'No active benchmark session; nothing to restore.'
        return
    }
    Assert-SessionMatchesTarget -Session $session -Paths $Paths
    Assert-OriginalBackups -Session $session

    $preRestorePath = Save-PreRestoreFiles -Paths $Paths -Session $session

    $originalDllTargets = [System.Collections.Generic.HashSet[string]]::new(
        [StringComparer]::OrdinalIgnoreCase)
    foreach ($record in @($session.Manifest.OriginalFiles |
        Where-Object { $_.Role -in @('TopLevelF4SEDll', 'LoadingScreensDll') })) {
        [void]$originalDllTargets.Add([string]$record.Target)
    }
    if (Test-Path -LiteralPath $Paths.F4SEPlugins -PathType Container) {
        foreach ($dll in @(Get-ChildItem -LiteralPath $Paths.F4SEPlugins -File -Filter '*.dll')) {
            if (-not $originalDllTargets.Contains($dll.FullName)) {
                Remove-Item -LiteralPath $dll.FullName -Force
            }
        }
    }

    foreach ($record in @($session.Manifest.OriginalFiles)) {
        Restore-OriginalRecord -SessionPath $session.SessionPath -Record $record
    }

    $session.Manifest.RestoredUtc = (Get-Date).ToUniversalTime().ToString('o')
    Write-JsonAtomic -LiteralPath $session.ManifestPath -Value $session.Manifest
    Remove-Item -LiteralPath $script:ActivePointerPath -Force

    Write-Host 'Restored every file captured at the start of the benchmark session.'
    Write-Host "Session retained at: $($session.SessionPath)"
    Write-Host "The final staged state was preserved at: $preRestorePath"
}

function Get-ActivePluginNames {
    param([Parameter(Mandatory = $true)][string]$PluginsPath)
    if (-not (Test-Path -LiteralPath $PluginsPath -PathType Leaf)) {
        return @()
    }
    return @(Get-Content -LiteralPath $PluginsPath | Where-Object {
        $_ -match '^\s*\*'
    } | ForEach-Object {
        ($_ -replace '^\s*\*', '').Trim()
    })
}

function Invoke-Status {
    param([Parameter(Mandatory = $true)]$Paths)

    Write-Host "Workspace: $script:WorkspaceRoot"
    Write-Host "Game root: $($Paths.GameRoot)"
    if (Test-Path -LiteralPath $Paths.Runtime -PathType Leaf) {
        Write-Host "Runtime: $((Get-Item -LiteralPath $Paths.Runtime).VersionInfo.FileVersion)"
    } else {
        Write-Host 'Runtime: missing'
    }

    $running = @(Get-RunningGameProcesses)
    if ($running.Count -eq 0) {
        Write-Host 'Game process: stopped'
    } else {
        Write-Host ('Game process: {0}' -f (($running | ForEach-Object {
            '{0}({1})' -f $_.ProcessName, $_.Id
        }) -join ', '))
    }

    $session = Get-ActiveSession
    if ($null -eq $session) {
        Write-Host 'Benchmark session: none'
    } else {
        Write-Host "Benchmark session: $($session.SessionPath)"
        Write-Host "Current variant: $($session.Manifest.CurrentVariant)"
        Write-Host "Diagnostics: $($session.Manifest.CurrentDiagnostics)"
        Write-Host "Archives: $(@($session.Manifest.ArchiveHistory).Count)"
    }

    $dlls = @()
    if (Test-Path -LiteralPath $Paths.F4SEPlugins -PathType Container) {
        $dlls = @(Get-ChildItem -LiteralPath $Paths.F4SEPlugins -File -Filter '*.dll' |
            Sort-Object Name)
    }
    if ($dlls.Count -eq 0) {
        Write-Host 'Active top-level F4SE DLLs: none'
    } else {
        Write-Host 'Active top-level F4SE DLLs:'
        foreach ($dll in $dlls) {
            Write-Host ('  {0}  SHA-256={1}' -f $dll.Name, (Get-Sha256 -LiteralPath $dll.FullName))
        }
    }

    $activePlugins = @(Get-ActivePluginNames -PluginsPath $Paths.PluginsTxt)
    if ($activePlugins.Count -eq 0) {
        Write-Host 'Active plugins.txt entries: none'
    } else {
        Write-Host ('Active plugins.txt entries: {0}' -f ($activePlugins -join ', '))
    }

    if (Test-Path -LiteralPath $Paths.FalloutCustom -PathType Leaf) {
        $loose = @(Select-String -LiteralPath $Paths.FalloutCustom `
            -Pattern '^\s*bInvalidateOlderFiles\s*=' -ErrorAction SilentlyContinue |
            ForEach-Object { $_.Line.Trim() })
        if ($loose.Count -gt 0) {
            Write-Host ('Loose-file setting: {0}' -f ($loose -join '; '))
        } else {
            Write-Host 'Loose-file setting: not explicitly set'
        }
    } else {
        Write-Host 'Loose-file setting: Fallout4Custom.ini missing'
    }

    if (Test-Path -LiteralPath $Paths.LoadingLog -PathType Leaf) {
        $log = Get-Item -LiteralPath $Paths.LoadingLog
        Write-Host ('LoadingScreens.log: {0} bytes, {1:o}' -f $log.Length, $log.LastWriteTimeUtc)
    } else {
        Write-Host 'LoadingScreens.log: missing'
    }
}

function Assert-BenchmarkSelfTest {
    param(
        [Parameter(Mandatory = $true)][bool]$Condition,
        [Parameter(Mandatory = $true)][string]$Message
    )
    if (-not $Condition) {
        throw "Benchmark harness self-test failed: $Message"
    }
}

function Assert-BenchmarkTextLine {
    param(
        [Parameter(Mandatory = $true)][string]$Text,
        [Parameter(Mandatory = $true)][string]$Expected
    )
    $lines = @($Text -split '\r?\n')
    Assert-BenchmarkSelfTest -Condition ($lines -contains $Expected) `
        -Message "generated configuration is missing '$Expected'"
}

function Invoke-SelfTest {
    $variant = 'gate-1cell'
