function Assert-NoUnexpectedActiveDlls {
    param(
        [Parameter(Mandatory = $true)]$Paths,
        [Parameter(Mandatory = $true)]$Session,
        [Parameter(Mandatory = $true)][string[]]$AllowedDllPaths
    )

    if (-not (Test-Path -LiteralPath $Paths.F4SEPlugins -PathType Container)) {
        return
    }
    $allowed = [System.Collections.Generic.HashSet[string]]::new(
        [StringComparer]::OrdinalIgnoreCase)
    foreach ($path in $AllowedDllPaths) {
        [void]$allowed.Add([IO.Path]::GetFullPath($path))
    }
    $active = @(Get-ChildItem -LiteralPath $Paths.F4SEPlugins -File -Filter '*.dll')
    $unexpected = @($active | Where-Object {
        -not $allowed.Contains($_.FullName)
    })
    if ($unexpected.Count -gt 0) {
        throw ('Unexpected F4SE DLL(s) appeared during the benchmark session: {0}. ' +
            'Move them out or run Restore before continuing.' -f
            (($unexpected | ForEach-Object Name) -join ', '))
    }
}

